/// Pending approvals cannot outlive a server process. Call during startup
/// before accepting new tool requests.
pub fn recover_proposals(conn: &mut Connection) -> Result<usize, String> {
    create_schema(conn)?;
    let tx = conn.transaction().map_err(|error| error.to_string())?;
    let pending = {
        let mut statement = tx
            .prepare("SELECT id,proposal_json FROM agent_proposals WHERE status='pending'")
            .map_err(|error| error.to_string())?;
        let rows = statement
            .query_map([], |row| {
                Ok((row.get::<_, String>(0)?, row.get::<_, String>(1)?))
            })
            .map_err(|error| error.to_string())?
            .collect::<Result<Vec<_>, _>>()
            .map_err(|error| error.to_string())?;
        rows
    };
    for (id, raw) in &pending {
        let mut proposal: ProposalRecord =
            serde_json::from_str(raw).map_err(|error| error.to_string())?;
        proposal.status = "stale".into();
        tx.execute(
            "UPDATE agent_proposals SET proposal_json=?2,status='stale',resolved_at=?3,resolved_by='recovery' WHERE id=?1 AND status='pending'",
            params![id, serde_json::to_string(&proposal).map_err(|error| error.to_string())?, store::now()],
        )
        .map_err(|error| error.to_string())?;
        if store::read_task(&tx, &proposal.caller_task_id)?.is_some() {
            let mut journal = Journal::new(&tx);
            journal.record_proposal(
                &proposal.caller_task_id,
                &serde_json::to_value(&proposal).map_err(|error| error.to_string())?,
            )?;
        }
    }
    tx.commit().map_err(|error| error.to_string())?;
    Ok(pending.len())
}

fn transition_proposal(
    tx: &Transaction<'_>,
    proposal: &mut ProposalRecord,
    status: &str,
    agent_id: Option<&str>,
    resolved_at_ms: i64,
) -> Result<ProposalReceipt, String> {
    proposal.status = status.to_owned();
    proposal.agent_id = agent_id.map(str::to_owned);
    let changed = tx.execute(
        "UPDATE agent_proposals SET proposal_json=?2,status=?3,resolved_agent_id=?4,resolved_at=?5,resolved_by='admin' WHERE id=?1 AND status='pending'",
        params![
            proposal.proposal_id,
            serde_json::to_string(proposal).map_err(|error| error.to_string())?,
            status,
            agent_id,
            timestamp(resolved_at_ms),
        ],
    )
    .map_err(|error| error.to_string())?;
    if changed != 1 {
        return Err("proposal-resolved".into());
    }
    if store::read_task(tx, &proposal.caller_task_id)?.is_some() {
        let mut journal = Journal::new(tx);
        journal.record_proposal(
            &proposal.caller_task_id,
            &serde_json::to_value(&*proposal).map_err(|error| error.to_string())?,
        )?;
    }
    Ok(ProposalReceipt {
        proposal_id: proposal.proposal_id.clone(),
        status: status.into(),
        project_id: proposal.project_id.clone(),
        agent_id: agent_id.map(str::to_owned),
        workspace_revision: None,
    })
}

