fn effective_access_mode(task: &Value, journal: &TaskRow) -> Result<String, String> {
    let task_mode = match task.get("accessMode") {
        None | Some(Value::Null) => None,
        Some(Value::String(mode)) => Some(mode.as_str()),
        _ => return Err("access-invalid".into()),
    };
    match (journal.config.access_mode.as_deref(), task_mode) {
        (Some(config_mode), Some(task_mode)) => least_privilege(config_mode, task_mode),
        (Some(mode), None) | (None, Some(mode)) => {
            access_rank(mode).ok_or_else(|| String::from("access-invalid"))?;
            Ok(mode.to_owned())
        }
        (None, None) => Ok("manual".into()),
    }
}

fn effective_model(task: &Value, journal: &TaskRow) -> Option<String> {
    journal
        .config
        .model_id
        .clone()
        .or_else(|| optional_string(task, "cloudModel"))
        .or_else(|| optional_string(task, "codexModel"))
        .or_else(|| {
            task.get("binding")
                .and_then(Value::as_object)
                .and_then(|binding| binding.get("modelId"))
                .and_then(Value::as_str)
                .filter(|model| !model.is_empty())
                .map(str::to_owned)
        })
}

fn least_privilege(caller: &str, specialist: &str) -> Result<String, String> {
    let caller = access_rank(caller).ok_or("access-invalid")?;
    let specialist = access_rank(specialist).ok_or("access-invalid")?;
    Ok(if caller <= specialist {
        access_name(caller)
    } else {
        access_name(specialist)
    }
    .to_owned())
}

fn access_rank(mode: &str) -> Option<usize> {
    match mode {
        "restricted" => Some(0),
        "manual" => Some(1),
        "full" => Some(2),
        _ => None,
    }
}

fn access_name(rank: usize) -> &'static str {
    match rank {
        0 => "restricted",
        1 => "manual",
        _ => "full",
    }
}

