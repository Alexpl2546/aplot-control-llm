fn active_caller(
    conn: &Connection,
    caller_task_id: &str,
    caller_generation: u64,
) -> Result<ActiveCaller, String> {
    let saved = workspace::read_saved(conn)?.ok_or("workspace-missing")?;
    if saved["version"] != 2 {
        return Err("workspace-version".into());
    }
    let data = saved.get("data").cloned().ok_or("workspace-invalid")?;
    workspace::validate(&data)?;
    let task = data["tasks"]
        .as_array()
        .and_then(|tasks| tasks.iter().find(|task| task["id"] == caller_task_id))
        .cloned()
        .ok_or("task-not-active")?;
    if truthy(&task["archived"]) || truthy(&task["deletedAt"]) {
        return Err("task-not-active".into());
    }
    let journal = store::read_task(conn, caller_task_id)?.ok_or("task-not-active")?;
    if !journal.state.pending || !journal.state.live || journal.state.ended || journal.state.stopped
    {
        return Err("task-not-active".into());
    }
    match journal.state.native_generation {
        Some(generation) if generation == caller_generation => {}
        Some(_) => return Err("task-generation-stale".into()),
        None => return Err("task-generation-unavailable".into()),
    }
    Ok(ActiveCaller {
        saved,
        data,
        task,
        journal,
    })
}

